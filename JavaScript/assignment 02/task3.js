
let a = 8;
let b = 4;
let operator = "+";

// First operation: Addition
if (operator === "+") {
    console.log(a + b);
} else if (operator === "-") {
    console.log(a - b);
}

// Change operator to subtraction
operator = "-";

// Second operation: Subtraction
if (operator === "+") {
    console.log(a + b);
} else if (operator === "-") {
    console.log(a - b);
}
